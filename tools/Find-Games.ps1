<#
.SYNOPSIS
  Locates both games through Steam (registry + libraryfolders.vdf + appmanifest) and writes
  build/local.props with Game1Dir / Game2Dir for the build. Manual override: pass -Game1Dir / -Game2Dir.
#>
param(
    [string]$Game1Dir,
    [string]$Game2Dir,
    [string]$OutFile = (Join-Path (Split-Path -Parent $PSScriptRoot) 'build\local.props')
)

$ErrorActionPreference = 'Stop'
$AppIds = @{ Game1 = 782130; Game2 = 1112380 }

function Get-SteamLibraries {
    $roots = New-Object System.Collections.Generic.List[string]
    foreach ($key in 'HKCU:\Software\Valve\Steam', 'HKLM:\SOFTWARE\WOW6432Node\Valve\Steam', 'HKLM:\SOFTWARE\Valve\Steam') {
        $p = Get-ItemProperty -Path $key -ErrorAction SilentlyContinue
        foreach ($v in @($p.SteamPath, $p.InstallPath)) { if ($v) { $roots.Add(($v -replace '/', '\')) } }
    }
    $libs = New-Object System.Collections.Generic.List[string]
    foreach ($r in ($roots | Select-Object -Unique)) {
        $vdf = Join-Path $r 'steamapps\libraryfolders.vdf'
        if (-not (Test-Path -LiteralPath $vdf)) { continue }
        $libs.Add($r)
        foreach ($m in [regex]::Matches((Get-Content -LiteralPath $vdf -Raw), '"path"\s+"([^"]+)"')) {
            $libs.Add(($m.Groups[1].Value -replace '\\\\', '\'))
        }
    }
    $libs | Select-Object -Unique
}

function Find-SteamGame([int]$appId) {
    foreach ($lib in Get-SteamLibraries) {
        $acf = Join-Path $lib "steamapps\appmanifest_$appId.acf"
        if (-not (Test-Path -LiteralPath $acf)) { continue }
        $m = [regex]::Match((Get-Content -LiteralPath $acf -Raw -Encoding UTF8), '"installdir"\s+"([^"]+)"')
        if ($m.Success) {
            $dir = Join-Path $lib ("steamapps\common\" + $m.Groups[1].Value)
            if (Test-Path -LiteralPath $dir) { return $dir }
        }
    }
    return $null
}

if (-not $Game1Dir) { $Game1Dir = Find-SteamGame $AppIds.Game1 }
if (-not $Game2Dir) { $Game2Dir = Find-SteamGame $AppIds.Game2 }
if (-not $Game1Dir -and -not $Game2Dir) { throw 'Neither game found. Pass -Game1Dir / -Game2Dir.' }

$xml = @"
<Project>
  <!-- Generated by tools/Find-Games.ps1. Machine-specific, not committed. -->
  <PropertyGroup>
    <Game1Dir>$Game1Dir</Game1Dir>
    <Game2Dir>$Game2Dir</Game2Dir>
  </PropertyGroup>
</Project>
"@
Set-Content -LiteralPath $OutFile -Value $xml -Encoding UTF8
"Game1Dir = $Game1Dir"
"Game2Dir = $Game2Dir"
"Wrote $OutFile"
